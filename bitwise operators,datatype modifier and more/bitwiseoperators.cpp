//bitwise operator "&"
#include<iostream>
using namespace std;
int main(){
    int a=6,b=10;
    cout<<(a&b)<<endl;
}


//bitwise operator "|"
#include<iostream>
using namespace std;
int main(){
    int a=6,b=10;
    cout<<(a|b)<<endl;
}

//bitwise operator "^"
#include<iostream>
using namespace std;
int main(){
    int a=6,b=10;
    cout<<(a^b)<<endl;
}

//bitwise operator "<<"
#include<iostream>
using namespace std;
int main(){
    int a=10;
    cout<<(a<<2)<<endl;
}

//bitwise operator ">>"
#include<iostream>
using namespace std;
int main(){
    int a=10;
    cout<<(a>>1)<<endl;
}